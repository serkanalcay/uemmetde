let currentLang = 'tr';

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;

  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.add('bg-surface-container-lowest', 'text-primary', 'shadow-sm');
      btn.classList.remove('text-on-surface-variant');
    } else {
      btn.classList.remove('bg-surface-container-lowest', 'text-primary', 'shadow-sm');
      btn.classList.add('text-on-surface-variant');
    }
  });

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  localStorage.setItem('uemmet_lang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('uemmet_lang') || 'tr';
  setLanguage(savedLang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const selectedLang = e.currentTarget.dataset.lang;
      setLanguage(selectedLang);
    });
  });

  // Handle Form Submission
  const dispatchForm = document.getElementById('dispatchForm');
  const dispatchResponse = document.getElementById('dispatchResponse');

  if (dispatchForm) {
    dispatchForm.addEventListener('submit', (e) => {
      e.preventDefault();
      if (dispatchResponse) {
        const msg = currentLang === 'tr' 
          ? '✓ Cenaze bildiriminiz alınmıştır. Nöbetçi ekibimiz 15 dakika içinde sizinle iletişime geçecektir.'
          : '✓ Ihre Meldung wurde empfangen. Unser Notfallteam wird Sie innerhalb von 15 Minuten kontaktieren.';
        
        dispatchResponse.innerHTML = `<div class="p-space-md bg-primary-container text-on-primary font-bold rounded-lg text-center mt-space-md shadow">${msg}</div>`;
        dispatchForm.reset();

        setTimeout(() => {
          dispatchResponse.innerHTML = '';
        }, 10000);
      }
    });
  }
});
